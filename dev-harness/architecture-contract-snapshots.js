#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const SERVER = path.join(ROOT, 'ruyi-workbench', 'app', 'server.js');
const RULES = path.join(ROOT, 'ruyi-workbench', 'app', 'src', 'context-governance-rules.json');
const ROUTES = path.join(ROOT, 'docs', 'architecture', 'route-inventory.json');
const OUT = path.join(ROOT, 'docs', 'architecture', 'architecture-contract-snapshots.json');
const MARKDOWN = path.join(ROOT, 'docs', 'architecture', 'architecture-contract-snapshots.md');

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map(key => [key, stable(value[key])]));
}
function json(value) { return JSON.stringify(stable(value), null, 2) + '\n'; }
function hash(value) { return crypto.createHash('sha256').update(JSON.stringify(stable(value))).digest('hex'); }
function counts(values) {
  const out = {};
  for (const value of values) out[value] = (out[value] || 0) + 1;
  return stable(out);
}

function build() {
  delete require.cache[require.resolve(SERVER)];
  const server = require(SERVER);
  const rules = JSON.parse(fs.readFileSync(RULES, 'utf8'));
  const routes = JSON.parse(fs.readFileSync(ROUTES, 'utf8'));
  const history = [
    { role: 'user', content: 'task-' + 'A'.repeat(10000) },
    { role: 'assistant', content: 'ack' },
    { role: 'user', content: 'middle-' + 'B'.repeat(10000) },
    { role: 'assistant', content: 'ack' },
    { role: 'user', content: 'latest-' + 'C'.repeat(10000) },
    { role: 'assistant', content: 'ack' },
  ];
  const provider = { id: '__contract_snapshot__', model: 'snapshot-model', contextWindow: 10000 };
  const config = { autoCompactThreshold: 0.8 };
  const main = server.CompactionPlan.create({ scope: 'main', trigger: 'auto', history, provider, model: provider.model, config, conversationWindow: true });
  const forced = server.CompactionPlan.create({ scope: 'main', trigger: 'forced_400', history, provider, model: provider.model, config, conversationWindow: true });
  const subagent = server.CompactionPlan.create({ scope: 'subagent', trigger: 'auto', history, provider, model: provider.model, config });
  const tiers = server.NATIVE_TOOL_TIER || {};
  return {
    schema: 1,
    compaction: {
      ruleSchema: rules.schema,
      rulesSha256: hash(rules),
      promptSha256: hash(rules.summary.prompt),
      modelWindows: rules.modelWindows,
      overflowStatuses: rules.overflow.statuses,
      requiredSections: rules.summary.sections,
      plans: {
        main: server.CompactionPlan.snapshot(main),
        forced400: server.CompactionPlan.snapshot(forced),
        subagent: server.CompactionPlan.snapshot(subagent),
      },
      reseedSha256: {
        main: hash(server.CompactionPlan.reseed(main, 'summary')),
        forced400: hash(server.CompactionPlan.reseed(forced, 'summary')),
        subagent: hash(server.CompactionPlan.reseed(subagent, 'summary')),
      },
    },
    persistence: {
      durableJsonStoreApi: Object.keys(server.DurableJsonStore || {}).sort(),
      storeInstanceApi: Object.keys(server.DurableJsonStore.create({ id: 'snapshot', file: path.join(ROOT, '.snapshot-never-written.json'), defaultValue: () => ({ schema: 1 }), schemaVersion: 1 })).sort(),
    },
    permission: {
      modes: server.PERMISSION_MODES,
      nativeToolCount: Object.keys(tiers).length,
      tierCounts: counts(Object.values(tiers)),
      tierMapSha256: hash(tiers),
    },
    routing: {
      routeAuthEntries: routes.summary.routeAuthEntries,
      decisionPoints: routes.summary.decisionPoints,
      problems: routes.summary.problems,
      warnings: routes.summary.warnings,
      routeAuthSha256: hash(routes.routeAuth),
      runtimeRouteAuthSha256: hash(server.ROUTE_AUTH),
    },
  };
}

function markdown(snapshot) {
  return `# Architecture contract snapshots\n\n`
    + `Wave 104 zero-behavior contract gate. Generated by \`dev-harness/architecture-contract-snapshots.js\`; do not hand-edit.\n\n`
    + `| Contract | Snapshot |\n|---|---|\n`
    + `| Compaction | rules schema ${snapshot.compaction.ruleSchema}; three shared CompactionPlan profiles; prompt ${snapshot.compaction.promptSha256.slice(0, 12)} |\n`
    + `| Persistence | DurableJsonStore API: ${snapshot.persistence.durableJsonStoreApi.join(', ')} |\n`
    + `| Permission | ${snapshot.permission.nativeToolCount} native tool tiers; modes ${snapshot.permission.modes.join(', ')} |\n`
    + `| Routing | ${snapshot.routing.decisionPoints} decision points / ${snapshot.routing.routeAuthEntries} auth rows / ${snapshot.routing.problems} problems |\n`;
}

const snapshot = build();
if (process.argv.includes('--write')) {
  fs.writeFileSync(OUT, json(snapshot));
  fs.writeFileSync(MARKDOWN, markdown(snapshot));
  console.log('architecture contract snapshots written');
} else {
  const expectedJson = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const expectedMarkdown = fs.existsSync(MARKDOWN) ? fs.readFileSync(MARKDOWN, 'utf8') : '';
  if (expectedJson !== json(snapshot) || expectedMarkdown !== markdown(snapshot)) {
    console.error('architecture contract snapshots drifted; run with --write and review');
    process.exit(1);
  }
  console.log('architecture contract snapshots current');
}
