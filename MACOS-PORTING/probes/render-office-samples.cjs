'use strict';
// Render only the fixed P3-02 sample set, using a private Office profile/cache.
// Usage: node MACOS-PORTING/probes/render-office-samples.cjs <generated sample directory>
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const { fixtureChildEnv } = require('../../dev-harness/lib/fixture-home');
if (!process.argv[2]) throw new Error('Pass the isolated sample directory generated by macos-office-artifacts.e2e.js');
const root = path.resolve(process.argv[2]);
const inputs = ['report.docx', 'data.xlsx', 'slides.pptx'].map(name => path.join(root, name));
for (const file of inputs) if (!fs.statSync(file).isFile()) throw new Error('Missing sample: ' + file);
// A converter can exit 0 after rejecting an input. A fresh destination ensures
// that old PDFs can never make the current render appear successful.
const out = fs.mkdtempSync(path.join(root, 'renders-'));
const fixture = fixtureChildEnv({ perTest: true });
const env = { ...fixture.env, XDG_CACHE_HOME: path.join(fixture.home, 'cache'), TMPDIR: path.join(fixture.home, 'tmp'),
  FONTCONFIG_FILE: path.join(fixture.home, 'fonts.conf') };
fs.mkdirSync(env.TMPDIR, { recursive: true });
// This bundled headless renderer otherwise only sees its bundled Latin fonts.
// Point its private Fontconfig at the installed Mac fonts without copying them.
fs.writeFileSync(env.FONTCONFIG_FILE,
  '<?xml version="1.0"?><!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd"><fontconfig>' +
  '<dir>/System/Library/Fonts</dir><dir>/Library/Fonts</dir><cachedir>' +
  path.join(fixture.home, 'font-cache') + '</cachedir></fontconfig>');
try {
  const args = ['-env:UserInstallation=' + new URL('file://' + path.join(fixture.home, 'libreoffice')).href,
    '--headless', '--convert-to', 'pdf', '--outdir', out, ...inputs];
  process.stdout.write(cp.execFileSync(process.env.RUYI_OFFICE_RENDERER || 'soffice', args,
    { env, encoding: 'utf8', timeout: 60000, maxBuffer: 2 * 1024 * 1024 }));
  for (const name of ['report', 'data', 'slides']) {
    const header = fs.readFileSync(path.join(out, name + '.pdf')).subarray(0, 5).toString();
    if (header !== '%PDF-') throw new Error('Renderer did not produce a PDF for ' + name);
  }
  console.log('RENDER_DIR=' + out);
} finally { fs.rmSync(fixture.home, { recursive: true, force: true }); }
